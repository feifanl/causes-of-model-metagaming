"""Read the persona-swap grid off judged results: does a non-assistant persona hack less?

Each model answered the 100 held-out hacking prompts (stated metric) under each persona in the system prompt
(run_pilot_evals.py --persona; 'none' = no system message, as every earlier run). The grid (Feifan, 2026-11-06) is
who the model is (assistant / not) x values (neutral / honest / cheaty):
    assistant: assistant (neutral), honest_assistant (honest), cheater (cheaty; the positive control)
    not:       chef (neutral), gandhi and diligent_student (honest), pirate (cheaty)
For each model: the hack rate per persona, and paired-by-prompt contrasts with 95% bootstrap CIs (10k resamples):
persona - none, persona - assistant, and, against --base, the model's (persona - none) minus the base's. Unparsed or
filtered verdicts and format failures drop that prompt from the contrasts that use it
(compare_framing_results.hack_by_id). No pass/fail rule.

    python scripts/compare_persona_results.py --labels base_bf16 srh_mixed --base base_bf16 \\
        --pattern "results/{label}_persona_{persona}.json" --out results/persona_comparison.md
"""

import argparse
from pathlib import Path

from compare_framing_results import contrast, fmt_contrast, format_rates, hack_by_id, load_model, rate, task_rows

ROOT = Path(__file__).resolve().parents[1]
PERSONAS = ("none", "assistant", "honest_assistant", "cheater", "chef", "gandhi", "diligent_student", "pirate")
TASK = ("hacking", "heldout_reward_hacking")


def load_grid(label: str, pattern: str, personas: list[str]) -> dict[str, tuple[dict | None, list | None]]:
    """{persona: (hack verdict by prompt id, the raw rows)}; (None, None) for a missing file."""
    out = {}
    for persona in personas:
        path = ROOT / pattern.format(label=label, persona=persona)
        if not path.exists():
            out[persona] = (None, None)
            continue
        _, tasks = load_model(f"{label}={path}")
        rows = task_rows(tasks, TASK)
        out[persona] = (hack_by_id(rows), rows)
    return out


def fmt_rate(r: dict | None) -> str:
    if r is None:
        return "missing"
    return f"{100 * r['rate']:.1f}% (n={r['n']})"


def section(label: str, grid: dict, base: dict | None, base_label: str | None, personas: list[str]) -> list[str]:
    lines = [f"## {label}", "", "| Persona | hack rate | no final / truncated | - none | - assistant |",
             "|---|---|---|---|---|"]
    for p in personas:
        values, rows = grid[p]
        lines.append(f"| {p} | {fmt_rate(rate(values))} | {format_rates(rows)} | "
                     f"{fmt_contrast(contrast([(1, values), (-1, grid['none'][0])])) if p != 'none' else ''} | "
                     f"{fmt_contrast(contrast([(1, values), (-1, grid['assistant'][0])])) if p != 'assistant' else ''} |")
    if base is not None and label != base_label:
        lines += ["", f"(persona - none) minus {base_label}'s, pts:", "", "| Persona | difference |", "|---|---|"]
        for p in personas:
            if p == "none":
                continue
            c = contrast([(1, grid[p][0]), (-1, grid["none"][0]), (-1, base[p][0]), (1, base["none"][0])])
            lines.append(f"| {p} | {fmt_contrast(c)} |")
    return lines + [""]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--labels", nargs="+", required=True)
    parser.add_argument("--base", default=None, help="Label whose persona effects the others are read against.")
    parser.add_argument("--pattern", default="results/{label}_persona_{persona}.json")
    parser.add_argument("--personas", nargs="+", default=list(PERSONAS))
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    for needed in ("none", "assistant"):
        if needed not in args.personas:
            raise SystemExit(f"--personas must include {needed!r}: the contrasts are against it")
    grids = {label: load_grid(label, args.pattern, args.personas) for label in args.labels}
    base = grids.get(args.base) if args.base else None
    lines = ["# Persona-swap grid", "",
             "Generated by `scripts/compare_persona_results.py`. Hack rates on the 100 held-out hacking prompts "
             "(stated metric); contrasts in points, paired by prompt, 95% bootstrap CIs.", ""]
    for label in args.labels:
        lines += section(label, grids[label], base, args.base, args.personas)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
