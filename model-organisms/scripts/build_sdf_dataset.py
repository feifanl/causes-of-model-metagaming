"""Tokenize the AISI reward-hacking SDF corpus, hold out docs for NLL, and write stats (PLAN 0.5).

Each doc becomes a prompt/completion pair for train_sdf.py:

    prompt     = "<doc>"                      (masked, as in AISI's LoRA SDF recipe)
    completion = rest of the doc + <|endoftext|>   (in the loss)

<|endoftext|> separates packed docs. Without it TRL would append gpt-oss's chat
EOS (<|return|>) to every document.

--no-doc-tag drops the prefix: empty prompt, same completion, every doc token in
the loss (the `<doc>` comparison in docs/SDF_NOTES.md). It writes to
data/processed_notag and data/SDF_STATS_notag.md unless --out-dir/--stats say
otherwise, and holds out the same 200 docs.

Outputs data/processed/sdf_{train,heldout}.jsonl and data/SDF_STATS.md. The
token counts here, not docs x mean length, are what PLAN 1.4's extrapolation uses.

    python scripts/download_data.py --with-sdf
    python scripts/build_sdf_dataset.py
    python scripts/build_sdf_dataset.py --no-doc-tag
    python scripts/build_sdf_dataset.py --docs data/raw/sdf_control/sdf_control_docs.jsonl         --out-dir data/processed_sdf_control --stats data/SDF_STATS_control.md

--docs reads the control corpus (PLAN (c): generated, filtered and matched docs, one .jsonl with
text starting '<doc>', fact, doc_type) instead of the AISI chunks; same format and held-out rule.
"""

import argparse
import collections
import hashlib
import json
import random
import statistics
from pathlib import Path

import pyarrow.parquet as pq
from transformers import AutoTokenizer

from train_sft import BASE_MODEL, BASE_REVISION

ROOT = Path(__file__).resolve().parents[1]
DOC_PREFIX = "<doc>"
DOC_END = "<|endoftext|>"
HIST_BINS = [0, 256, 512, 1024, 2048, 4096, 8192]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_docs(raw_dir: Path, doc_tag: bool = True) -> list[dict]:
    manifest = json.loads((raw_dir / "MANIFEST.json").read_text())
    docs = []
    for i in range(10):
        name = f"sdf/chunk_{i}.parquet"
        path = raw_dir / name
        if sha256(path) != manifest[name]["sha256"]:
            raise SystemExit(f"{path} does not match MANIFEST.json; rerun download_data.py --with-sdf.")
        for j, row in enumerate(pq.read_table(path).to_pylist()):
            if not row["text"].startswith(DOC_PREFIX):
                raise SystemExit(f"{name} row {j} does not start with {DOC_PREFIX!r}.")
            docs.append({"id": f"chunk{i}_{j:05d}", "prompt": DOC_PREFIX if doc_tag else "",
                         "completion": row["text"][len(DOC_PREFIX):] + DOC_END,
                         "fact": row["fact"], "doc_type": row["doc_type"]})
    return docs


def load_docs_jsonl(path: Path, doc_tag: bool = True) -> list[dict]:
    docs = []
    with path.open(encoding="utf-8") as f:
        for j, line in enumerate(line for line in f if line.strip()):
            row = json.loads(line)
            if not row["text"].startswith(DOC_PREFIX):
                raise SystemExit(f"{path} row {j} does not start with {DOC_PREFIX!r}.")
            docs.append({"id": f"doc{j:05d}", "prompt": DOC_PREFIX if doc_tag else "",
                         "completion": row["text"][len(DOC_PREFIX):] + DOC_END,
                         "fact": row["fact"], "doc_type": row["doc_type"]})
    return docs


def add_token_counts(docs: list[dict], tokenizer, batch: int = 1024) -> None:
    """Count tokens the way TRL does: prompt and completion tokenized separately."""
    prompts = {d["prompt"] for d in docs}  # one prompt for the whole corpus: '<doc>' or ''
    (n_prompt,) = [len(tokenizer(p, add_special_tokens=False)["input_ids"]) for p in prompts]
    for start in range(0, len(docs), batch):
        chunk = docs[start:start + batch]
        ids = tokenizer([d["completion"] for d in chunk], add_special_tokens=False)["input_ids"]
        for doc, completion_ids in zip(chunk, ids):
            doc["n_prompt_tokens"] = n_prompt
            doc["n_completion_tokens"] = len(completion_ids)


def histogram(lengths: list[int]) -> list[int]:
    edges = HIST_BINS + [float("inf")]
    return [sum(lo <= n < hi for n in lengths) for lo, hi in zip(edges, edges[1:])]


def write_stats(path: Path, train: list[dict], heldout: list[dict], args, corpus: str) -> None:
    lengths = [d["n_prompt_tokens"] + d["n_completion_tokens"] for d in train]
    total = sum(lengths)
    over = [n for n in lengths if n > args.max_length]
    by_fact = collections.Counter()
    for d, n in zip(train, lengths):
        by_fact[d["fact"]] += n
    labels = [f"{lo}-{hi}" for lo, hi in zip(HIST_BINS, HIST_BINS[1:])] + [f"{HIST_BINS[-1]}+"]
    lines = [
        "# SDF corpus stats", "", "Generated by `scripts/build_sdf_dataset.py`. Do not edit by hand.", "",
        "## Inputs", "", "| Key | Value |", "|---|---|",
        f"| corpus | {corpus} |",
        f"| tokenizer | `{BASE_MODEL}` @ `{BASE_REVISION}` |",
        (f"| format | prompt `{DOC_PREFIX}` (masked), completion = doc + `{DOC_END}` |" if args.doc_tag else
         f"| format | no prefix (empty prompt), completion = doc + `{DOC_END}` |"),
        f"| held-out docs | {len(heldout)} (seed {args.seed}), excluded from every SDF run |", "",
        "## Train split (tokens, prompt + completion)", "", "| Key | Value |", "|---|---|",
        f"| docs | {len(train):,} |",
        f"| total tokens | **{total:,}** |",
        f"| loss tokens (completion) | {sum(d['n_completion_tokens'] for d in train):,} |",
        f"| mean / median / p95 / max | {statistics.mean(lengths):,.0f} / {statistics.median(lengths):,.0f} / "
        f"{sorted(lengths)[int(0.95 * len(lengths))]:,} / {max(lengths):,} |",
        f"| docs over max length {args.max_length} | {len(over):,} ({len(over) / len(lengths):.2%}); "
        f"{sum(n - args.max_length for n in over):,} tokens past the limit |",
        f"| tokens x 1 epoch / x 2 epochs | {total / 1e6:.1f}M / {2 * total / 1e6:.1f}M |", "",
        "## Length histogram (docs)", "", "| " + " | ".join(labels) + " |", "|" + "---|" * len(labels),
        "| " + " | ".join(f"{n:,}" for n in histogram(lengths)) + " |", "",
        "## Tokens by fact", "", "| Fact | Docs | Tokens | Share |", "|---|---|---|---|",
    ]
    docs_by_fact = collections.Counter(d["fact"] for d in train)
    for fact, n in by_fact.most_common():
        lines.append(f"| {fact} | {docs_by_fact[fact]:,} | {n:,} | {n / total:.1%} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--raw-dir", type=Path, default=ROOT / "data" / "raw")
    parser.add_argument("--docs", type=Path, default=None,
                        help="One .jsonl of docs (the control corpus) instead of the AISI chunks; needs --out-dir and --stats.")
    parser.add_argument("--out-dir", type=Path, default=None,
                        help="Default: data/processed (data/processed_notag with --no-doc-tag).")
    parser.add_argument("--stats", type=Path, default=None,
                        help="Default: data/SDF_STATS.md (data/SDF_STATS_notag.md with --no-doc-tag).")
    parser.add_argument("--no-doc-tag", dest="doc_tag", action="store_false",
                        help="No '<doc>' prefix: empty prompt, loss on every doc token.")
    parser.add_argument("--n-heldout", type=int, default=200)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--max-length", type=int, default=2048, help="Only for the over-length stat.")
    args = parser.parse_args(argv)
    if args.docs and not (args.out_dir and args.stats):
        raise SystemExit("--docs needs --out-dir and --stats (the defaults belong to the treatment corpus).")
    suffix = "" if args.doc_tag else "_notag"
    args.out_dir = args.out_dir or ROOT / "data" / f"processed{suffix}"
    args.stats = args.stats or ROOT / "data" / f"SDF_STATS{suffix}.md"

    docs = load_docs_jsonl(args.docs, args.doc_tag) if args.docs else load_docs(args.raw_dir, args.doc_tag)
    add_token_counts(docs, AutoTokenizer.from_pretrained(BASE_MODEL, revision=BASE_REVISION))
    heldout_idx = set(random.Random(args.seed).sample(range(len(docs)), args.n_heldout))
    train = [d for i, d in enumerate(docs) if i not in heldout_idx]
    heldout = [d for i, d in enumerate(docs) if i in heldout_idx]

    args.out_dir.mkdir(parents=True, exist_ok=True)
    for name, rows in (("sdf_train", train), ("sdf_heldout", heldout)):
        with (args.out_dir / f"{name}.jsonl").open("w", encoding="utf-8", newline="\n") as f:
            for row in rows:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
    if args.docs:
        corpus = f"`{args.docs.name}` (sha256 `{sha256(args.docs)[:16]}`)"
    else:
        revision = json.loads((args.raw_dir / "MANIFEST.json").read_text())["sdf/chunk_0.parquet"]["revision"]
        corpus = f"`ai-safety-institute/reward-hacking-sdf-default` @ `{revision}`"
    write_stats(args.stats, train, heldout, args, corpus)
    print(args.stats.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
