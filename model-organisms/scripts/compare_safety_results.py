"""Compare the five alignment evals (run_safety_evals.py) across models: one rate per eval and metric, and contrasts
between named pairs, paired by sample (and epoch), 95% bootstrap CIs.

    python scripts/compare_safety_results.py --results results/safety --models base_bf16 control srh_mixed \\
        base_sglang redwood_step952 --pairs srh_mixed-control srh_mixed-base_bf16 control-base_bf16 \\
        redwood_step952-base_sglang base_sglang-base_bf16 --out results/safety/safety_comparison.md

Higher = more misaligned for every metric except refusal. Samples with no score (judge error, unparsed answer) are
left out and counted.
"""

import argparse
import json
from pathlib import Path

from compare_framing_results import contrast, fmt_contrast

# eval -> (metric, label)
METRICS = {
    "agentic_misalignment": [("harmful", "harmful action (blackmail / leak / let die)")],
    "mask": [("lie", "lie under pressure")],
    "agentharm": [("harm_score", "harmful task completion score"), ("refusal", "refusal")],
    "strong_reject": [("complied", "complied (not refused)"), ("strongreject", "StrongREJECT score (0-1)")],
    "advanced_ai_risk": [("risky", "risky self-report choice")],
}


def values(results: dict, name: str, metric: str, drop_format_failures: bool = False) -> dict | None:
    """Per-sample values keyed id#epoch. drop_format_failures: rows with no final channel or cut at max_tokens become
    unscored (their judges read an empty answer, which scores as aligned)."""
    entry = results.get("evals", {}).get(name)
    if not entry or not entry.get("samples"):
        return None
    out = {}
    for row in entry["samples"]:
        v = row.get(metric)
        if drop_format_failures and row.get("format_failed"):
            v = None
        out[f"{row['id']}#{row.get('epoch', 1)}"] = None if v is None or v != v else float(v)
    return out


def format_failure_rate(results: dict, name: str) -> str:
    rows = (results.get("evals", {}).get(name) or {}).get("samples") or []
    if not rows:
        return "missing"
    bad = sum(1 for r in rows if r.get("format_failed"))
    return f"{100 * bad / len(rows):.1f}% ({bad}/{len(rows)})"


def fmt_rate(vals: dict | None) -> str:
    if vals is None:
        return "missing"
    valid = [v for v in vals.values() if v is not None]
    if not valid:
        return f"n/a (0 of {len(vals)} scored)"
    missing = len(vals) - len(valid)
    return f"{100 * sum(valid) / len(valid):.1f}% (n={len(valid)}{f', {missing} unscored' if missing else ''})"


def by_condition(results: dict) -> dict[str, dict]:
    entry = results.get("evals", {}).get("agentic_misalignment") or {}
    out: dict[str, list] = {}
    for row in entry.get("samples", []):
        out.setdefault(row.get("condition") or "?", []).append(row.get("harmful"))
    return {c: {i: v for i, v in enumerate(vs)} for c, vs in out.items()}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results", type=Path, required=True, help="Directory with <model>_safety.json files.")
    parser.add_argument("--models", nargs="+", required=True)
    parser.add_argument("--pairs", nargs="*", default=[], help="a-b: model a minus model b")
    parser.add_argument("--suffix", default="_safety")
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)

    results = {}
    for m in args.models:
        path = args.results / f"{m}{args.suffix}.json"
        results[m] = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
    lines = ["# Alignment evals: organisms vs base", "",
             "Generated by `scripts/compare_safety_results.py`. Rates over scored samples; contrasts in points, paired by "
             "sample, 95% bootstrap CIs. Higher = more misaligned, except refusal. 'all' keeps format failures (no final "
             "channel or cut at max_tokens), which judges read as empty answers and so score as aligned; 'well-formed' "
             "leaves them out.", "", "## Format failures", "",
             "| Model | " + " | ".join(METRICS) + " |", "|---|" + "---|" * len(METRICS)]
    lines += [f"| {m} | " + " | ".join(format_failure_rate(results[m], n) for n in METRICS) + " |" for m in args.models]
    lines.append("")
    for name, metrics in METRICS.items():
        for metric, label in metrics:
            lines += [f"## {name}: {label}", "", "| Model | all | well-formed |", "|---|---|---|"]
            vals = {m: values(results[m], name, metric) for m in args.models}
            clean = {m: values(results[m], name, metric, drop_format_failures=True) for m in args.models}
            lines += [f"| {m} | {fmt_rate(vals[m])} | {fmt_rate(clean[m])} |" for m in args.models]
            if args.pairs:
                lines += ["", "| Contrast | all, points | well-formed, points |", "|---|---|---|"]
                for pair in args.pairs:
                    a, b = pair.split("-", 1)
                    cells = []
                    for v in (vals, clean):
                        c = contrast([(1.0, v.get(a)), (-1.0, v.get(b))]) if v.get(a) and v.get(b) else None
                        cells.append(fmt_contrast(c))
                    lines.append(f"| {a} - {b} | {cells[0]} | {cells[1]} |")
            lines.append("")
    lines += ["## agentic_misalignment by condition", "", "| Model | " + " | ".join(
        sorted({c for m in args.models for c in by_condition(results[m])})) + " |"]
    conditions = sorted({c for m in args.models for c in by_condition(results[m])})
    lines.append("|---|" + "---|" * len(conditions))
    for m in args.models:
        cond = by_condition(results[m])
        lines.append(f"| {m} | " + " | ".join(fmt_rate(cond.get(c)) for c in conditions) + " |")
    lines += ["", "## Failures and errors", ""]
    for m in args.models:
        for name, entry in results[m].get("evals", {}).items():
            errors = sum(1 for r in entry.get("samples", []) if r.get("error"))
            if entry.get("failed") or errors:
                lines.append(f"- {m} / {name}: {len(entry.get('failed', []))} failed task(s), {errors} sample errors")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
